let locale = localStorage.getItem("dev-mesh-locale") || (navigator.language.startsWith("zh") ? "zh" : "en");

export function language() {
  return locale;
}

export function t(key, values = null) {
  const message = messages[locale]?.[key] ?? messages.en[key] ?? key;
  if (!values) return message;
  return message.replace(/\{(\w+)\}/g, (whole, name) => (
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : whole
  ));
}

export function eventLabel(event) {
  return t(`event.${event}`) === `event.${event}` ? t("event.default") : t(`event.${event}`);
}

export function diagnosticLabel(code) {
  const key = `diagnostic.${code}`;
  return t(key) === key ? code : t(key);
}

export function toggleLanguage() {
  locale = locale === "zh" ? "en" : "zh";
  localStorage.setItem("dev-mesh-locale", locale);
  applyTranslations();
  return locale;
}

export function applyTranslations() {
  document.documentElement.lang = locale === "zh" ? "zh-CN" : "en";
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    node.setAttribute("aria-label", t(node.dataset.i18nAria));
  });
}
